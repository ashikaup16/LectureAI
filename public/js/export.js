/**
 * Export and Clipboard Utilities for LectureAI
 */

const ExportManager = {
  /**
   * Copy formatted text to clipboard
   */
  async copyToClipboard(text, successMsg = 'Copied to clipboard!') {
    try {
      await navigator.clipboard.writeText(text);
      if (window.showToast) {
        window.showToast(successMsg, 'success');
      }
    } catch (err) {
      // Fallback
      const ta = document.createElement('textarea');
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      document.body.removeChild(ta);
      if (window.showToast) {
        window.showToast(successMsg, 'success');
      }
    }
  },

  /**
   * Trigger file download in browser
   */
  downloadFile(filename, content, mimeType = 'text/plain;charset=utf-8;') {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    if (window.showToast) {
      window.showToast(`Saved ${filename}`, 'success');
    }
  },

  /**
   * Format full lecture packet as Markdown
   */
  generateFullMarkdown(data) {
    const { metadata, summary, notes, quiz, flashcards } = data;
    let md = `# ${metadata.title}\n`;
    md += `**Presenter / Source**: ${metadata.author}\n`;
    md += `**Duration**: ${data.transcript ? data.transcript.formattedDuration : 'N/A'}\n\n`;

    if (summary) {
      md += `## Executive Summary\n${summary.tldr}\n\n`;
      if (summary.keyTakeaways && summary.keyTakeaways.length > 0) {
        md += `### Key Takeaways\n`;
        summary.keyTakeaways.forEach(k => {
          md += `- ${k.icon || '•'} **[${k.timestamp || ''}]** ${k.text}\n`;
        });
        md += `\n`;
      }
    }

    if (notes && notes.markdown) {
      md += notes.markdown + `\n\n`;
    }

    if (quiz && quiz.questions) {
      md += `## Knowledge Check Quiz\n\n`;
      quiz.questions.forEach((q, i) => {
        md += `### Question ${i + 1}: ${q.question}\n`;
        q.options.forEach((opt, optIdx) => {
          const isCorrect = optIdx === q.correctAnswerIndex ? ' (Correct Answer)' : '';
          md += `- ${String.fromCharCode(65 + optIdx)}) ${opt}${isCorrect}\n`;
        });
        md += `\n*Explanation*: ${q.explanation}\n\n`;
      });
    }

    if (flashcards && flashcards.length > 0) {
      md += `## Key Flashcards & Definitions\n\n`;
      flashcards.forEach((f, i) => {
        md += `**Q${i + 1}**: ${f.front}\n`;
        md += `**A**: ${f.back}\n\n`;
      });
    }

    md += `---\n*Generated by LectureAI: AI-Powered Academic Assistant*\n`;
    return md;
  },

  /**
   * Export as PDF via browser print
   */
  exportPDF() {
    window.print();
  }
};

window.ExportManager = ExportManager;
